/**
 * Normalizes text for matching by removing accents, punctuation, and extra whitespace
 * @param {string} str
 * @returns {string}
 */
export function normalizeLocationString(str) {
	if (!str || typeof str !== 'string') return '';
	return str
		.normalize('NFD')
		.replace(/[\u0300-\u036f]/g, '') // remove diacritics (e.g. ñ -> n)
		.replace(/[.,\-_/()]/g, ' ')
		.replace(/\s+/g, ' ')
		.trim()
		.toLowerCase();
}

/**
 * Resolves any raw candidate string or OpenStreetMap / Nominatim address object
 * to the exact, official recognized Philippine City or Municipality name
 * (e.g. "Davao" -> "Davao City", "Antipolo" -> "Antipolo City", "Makati" -> "Makati City", "Taytay" -> "Taytay").
 * 
 * @param {string|object} input - A string or a Nominatim response / address object
 * @param {string} [provinceHint] - Optional province or region hint
 * @returns {{ city: string, province: string, region: string, isOfficial: boolean }}
 */
export function resolvePhilippineCity(input, provinceHint = '') {
	if (!input) {
		return { city: '', province: '', region: '', isOfficial: false };
	}

	const candidates = [];
	let provHintNorm = normalizeLocationString(provinceHint);

	if (typeof input === 'object' && input !== null) {
		const addr = input.address || input;
		if (addr.province || addr.state || addr.region) {
			provHintNorm = normalizeLocationString(addr.province || addr.state || addr.region);
		}

		// Collect candidates in priority order
		if (addr.city) candidates.push(addr.city);
		if (addr.town) candidates.push(addr.town);
		if (addr.municipality) candidates.push(addr.municipality);
		if (addr.city_district) candidates.push(addr.city_district);
		if (addr.county) candidates.push(addr.county);
		if (addr.suburb) candidates.push(addr.suburb);
		if (addr.village) candidates.push(addr.village);
		if (addr.quarter) candidates.push(addr.quarter);

		if (input.display_name && typeof input.display_name === 'string') {
			const parts = input.display_name.split(',').map(p => p.trim());
			candidates.push(...parts);
		}
	} else if (typeof input === 'string') {
		candidates.push(input);
		if (input.includes(',')) {
			const parts = input.split(',').map(p => p.trim());
			candidates.push(...parts);
		}
	}

	// 1. Exact & Base-name match pass against PH_CITIES_MUNICIPALITIES
	for (const cand of candidates) {
		const candNorm = normalizeLocationString(cand);
		if (!candNorm || candNorm.length < 2) continue;

		// 1a. Exact match with official name (e.g. "davao city" === "davao city")
		for (const item of PH_CITIES_MUNICIPALITIES) {
			const itemNorm = normalizeLocationString(item.city);
			if (candNorm === itemNorm) {
				return {
					city: item.city,
					province: item.province,
					region: item.region,
					isOfficial: true
				};
			}
		}

		// 1b. Base name match (e.g. "davao" matches "davao city", "antipolo" matches "antipolo city")
		for (const item of PH_CITIES_MUNICIPALITIES) {
			const baseNorm = normalizeLocationString(item.city.replace(/ city$/i, ''));
			if (candNorm === baseNorm) {
				// Disambiguate with province hint if multiple entries share base name
				if (provHintNorm) {
					const itemProvNorm = normalizeLocationString(item.province);
					if (provHintNorm.includes(itemProvNorm) || itemProvNorm.includes(provHintNorm)) {
						return {
							city: item.city,
							province: item.province,
							region: item.region,
							isOfficial: true
						};
					}
				}
				return {
					city: item.city,
					province: item.province,
					region: item.region,
					isOfficial: true
				};
			}
		}
	}

	// 2. Prefix / Contains match pass (e.g. "city of manila", "quezon city hall", "davao del sur" checks)
	for (const cand of candidates) {
		const candNorm = normalizeLocationString(cand);
		if (!candNorm || candNorm.length < 3) continue;

		for (const item of PH_CITIES_MUNICIPALITIES) {
			const itemNorm = normalizeLocationString(item.city);
			const baseNorm = normalizeLocationString(item.city.replace(/ city$/i, ''));

			if (
				candNorm === `city of ${baseNorm}` ||
				candNorm.startsWith(`${itemNorm} `) ||
				candNorm.startsWith(`${baseNorm} `) ||
				candNorm.endsWith(` ${itemNorm}`) ||
				candNorm.endsWith(` ${baseNorm}`)
			) {
				return {
					city: item.city,
					province: item.province,
					region: item.region,
					isOfficial: true
				};
			}
		}
	}

	// 3. Fallback: return best candidate from OpenStreetMap
	const fallbackRaw = candidates[0] || (typeof input === 'string' ? input : '');
	let fallbackClean = fallbackRaw.trim();
	if (fallbackClean) {
		return {
			city: fallbackClean,
			province: provinceHint || '',
			region: '',
			isOfficial: false
		};
	}

	return { city: '', province: '', region: '', isOfficial: false };
}

/**
 * Searches local PH location database and optionally supplements with Nominatim OpenStreetMap API
 * @param {string} query
 * @returns {Promise<Array<{ city: string, province: string, region?: string, displayName: string, isFromApi?: boolean }>>}
 */
export async function searchPhilippineLocations(query) {
	if (!query || typeof query !== 'string' || !query.trim()) {
		return [];
	}

	const clean = query.trim().toLowerCase();
	const cleanNorm = normalizeLocationString(query);
	const results = [];
	const seenCities = new Set();

	// 1. Fast Local Search in PH_CITIES_MUNICIPALITIES
	for (const item of PH_CITIES_MUNICIPALITIES) {
		const cityName = item.city.toLowerCase();
		const provName = (item.province || '').toLowerCase();
		const regName = (item.region || '').toLowerCase();
		const baseCityNorm = normalizeLocationString(item.city.replace(/ city$/i, ''));
		const fullCityNorm = normalizeLocationString(item.city);

		// Match against city name or province
		if (
			fullCityNorm.includes(cleanNorm) ||
			baseCityNorm.includes(cleanNorm) ||
			cleanNorm.includes(baseCityNorm) ||
			provName.includes(clean) ||
			regName.includes(clean)
		) {
			const key = `${item.city.toLowerCase()}|${item.province.toLowerCase()}`;
			if (!seenCities.has(key)) {
				seenCities.add(key);
				results.push({
					city: item.city,
					province: item.province,
					region: item.region,
					displayName: `${item.city}, ${item.province}`,
					isFromApi: false
				});
			}
		}

		if (results.length >= 12) break;
	}

	// 2. Query OpenStreetMap Nominatim for exact landmarks/barangays or missing places
	if (results.length < 8 && clean.length >= 3) {
		try {
			const apiRes = await fetch(
				`https://nominatim.openstreetmap.org/search?format=json&countrycodes=ph&q=${encodeURIComponent(query)}&limit=6&addressdetails=1`,
				{
					headers: {
						'Accept-Language': 'en'
					}
				}
			);
			if (apiRes.ok) {
				const apiData = await apiRes.json();
				for (const item of apiData || []) {
					const addr = item.address || {};
					const resolvedCity = addr.city || addr.town || addr.municipality || addr.city_district || addr.suburb || addr.village || addr.county || '';
					const resolvedProvince = addr.province || addr.state || addr.region || '';

					if (resolvedCity) {
						// Resolve to official Philippine city if available (ensures "City" suffix if official)
						const official = resolvePhilippineCity(item);
						const cleanCity = official.isOfficial ? official.city : resolvedCity.trim();
						const cleanProvince = official.isOfficial ? official.province : (resolvedProvince || 'Philippines');
						const key = `${cleanCity.toLowerCase()}|${cleanProvince.toLowerCase()}`;
						if (!seenCities.has(key)) {
							seenCities.add(key);
							results.push({
								city: cleanCity,
								province: cleanProvince,
								region: official.region || addr.region || '',
								displayName: cleanProvince ? `${cleanCity}, ${cleanProvince}` : cleanCity,
								isFromApi: true
							});
						}
					}
				}
			}
		} catch (err) {
			console.warn('Live geocode search fallback error:', err);
		}
	}

	return results;
}

/**
 * Checks if a given city string is a recognized valid Philippine city / municipality
 * @param {string} city
 * @returns {boolean}
 */
export function isValidPhilippineLocation(city) {
	if (!city || typeof city !== 'string' || !city.trim()) return false;
	const cleanNorm = normalizeLocationString(city);
	
	// Check against local database
	return PH_CITIES_MUNICIPALITIES.some(item => {
		const fullNorm = normalizeLocationString(item.city);
		const baseNorm = normalizeLocationString(item.city.replace(/ city$/i, ''));
		return cleanNorm === fullNorm || cleanNorm === baseNorm || cleanNorm.startsWith(fullNorm) || cleanNorm.startsWith(baseNorm);
	});
}
